"""Regenerate tests/dump_abi.inc from the reference-VA registry.

The 64-bit write-set dump cannot link the 32-bit hook bodies. It resolves a
body name to the ORIGINAL destination VA instead, so an installer's rel32 is
comparable with the original build. Keep this table in sync when a registry row
changes.
"""

from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HOOKS = ROOT / "source/hooks.cpp"
OUT = ROOT / "tests/dump_abi.inc"


def main() -> int:
    text = HOOKS.read_text(encoding="utf-8")
    rows = re.findall(
        r"\{(0x[0-9A-Fa-f]+)u,\s*reinterpret_cast<void\(\*\)\(\)>\(&(abi_[A-Za-z0-9_]+)\)\}",
        text,
    )
    lines = ["// Generated by tools/gen_dump_abi.py from source/hooks.cpp."]
    lines += [f'{{"{name}", {va}u}},' for va, name in rows]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT} ({len(rows)} rows)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
