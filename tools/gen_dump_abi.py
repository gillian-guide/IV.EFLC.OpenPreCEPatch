"""Regenerate tests/dump_abi.inc from the per-module ABI registrations.

The 64-bit write-set dump cannot link the 32-bit hook bodies. It resolves a
body name to the ORIGINAL destination VA instead, so an installer's rel32 is
comparable with the original build. The rows live in the feature modules now
(each registers the bodies it owns); keep this table in sync with them.

Run with --check to verify the checked-in table instead of writing it.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "tests/dump_abi.inc"

# {"abi_name", 0x12345u, reinterpret_cast<opp::HookBody>(&abi_name)},
ROW = re.compile(
    r'\{"(abi_[A-Za-z0-9_]+)", 0x([0-9A-Fa-f]+)u, '
    r"reinterpret_cast<opp::HookBody>\(&"
)


def rows() -> dict[str, int]:
    table: dict[str, int] = {}
    for path in sorted((ROOT / "source").glob("*.ixx")):
        text = path.read_text(encoding="utf-8")
        for match in ROW.finditer(text):
            name = match.group(1)
            va = int(match.group(2), 16)
            if name in table:
                raise SystemExit(f"error: {name} registered twice")
            table[name] = va
    if not table:
        raise SystemExit("error: no ABI rows parsed")
    return table


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    table = rows()
    lines = ["// Generated by tools/gen_dump_abi.py from the feature modules."]
    lines += [f'{{"{name}", {va:#x}u}},' for name, va in sorted(table.items())]
    generated = "\n".join(lines) + "\n"
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != generated:
            print(f"stale: {OUT}")
            return 1
        print(f"ok: {OUT} is current ({len(table)} rows)")
        return 0
    OUT.write_text(generated, encoding="utf-8")
    print(f"wrote {OUT} ({len(table)} rows)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
