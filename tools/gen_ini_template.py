"""Regenerate source/ini_template.hxx from the shipped INI.

The ASI embeds `data/plugins/IV.EFLC.OpenPreCEPatch.ini` verbatim as a C++ raw
string, so the first-run template and the documented file cannot drift.
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
INI = ROOT / "data/plugins/IV.EFLC.OpenPreCEPatch.ini"
OUT = ROOT / "source/ini_template.hxx"

HEADER = """// SPDX-License-Identifier: GPL-3.0-or-later
//
// The shipped INI template. The ASI writes this next to itself on first run and
// uses it to port an existing ZolikaPatch.ini into the grouped layout.
//
// Generated by tools/gen_ini_template.py from
// data/plugins/IV.EFLC.OpenPreCEPatch.ini; do not edit by hand.

#pragma once

namespace opp
{
\tinline constexpr char kDefaultIni[] =
"""

FOOTER = """;
} // namespace opp
"""

# MSVC truncates a single string literal above 16380 bytes. Emit adjacent raw
# literals (the compiler concatenates them) split at line boundaries.
CHUNK = 12000


def chunks(text: str) -> list[str]:
    result: list[str] = []
    start = 0
    while start < len(text):
        end = min(start + CHUNK, len(text))
        if end < len(text):
            newline = text.rfind("\n", start, end)
            if newline > start:
                end = newline + 1
        result.append(text[start:end])
        start = end
    return result


def main() -> int:
    text = INI.read_text(encoding="utf-8")
    if ")OPCEP\"" in text:
        print("error: INI contains the raw-string terminator", file=sys.stderr)
        return 1
    if not text.endswith("\n"):
        text += "\n"
    body = "\n".join(f'R"OPCEP({part})OPCEP"' for part in chunks(text))
    OUT.write_text(HEADER + body + FOOTER, encoding="utf-8")
    print(f"wrote {OUT} ({len(text)} INI bytes, {len(chunks(text))} chunks)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
