"""Generate parity_globals.inc for the readable port from its rebased.h.

The table is the port's side of tools/parity/state_diff.py: one row per
`extern "C"` global, named exactly like the reconstruction's table so the
harness can look our values up by symbol.

Rows whose declaration has an incomplete array type (`[]`) are skipped: `sizeof`
cannot be applied to them, and the reference table skips the same set (its header
carries the same incomplete declarations). Everything else must be complete.

Usage: gen_parity_globals.py [--header H] [--out O]
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]

PAT = re.compile(
    r'extern\s+"C"\s+(?P<type>[A-Za-z_][\w:]*(?:\s+[A-Za-z_][\w:]*)*|unsigned\s+char)\s+'
    r"(?P<sym>zpatch_\w+)\s*(?P<arr>\[[^\]]*\])?\s*;(?:\s*//\s*(?P<note>.*))?$",
    re.M,
)


def parse(header: Path):
    rows, skipped = [], []
    for m in PAT.finditer(header.read_text(encoding="utf-8")):
        sym, arr = m.group("sym"), m.group("arr")
        if arr == "[]":
            skipped.append(sym)
            continue
        rows.append((sym, m.group("note") or ""))
    return rows, skipped


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--header", default=str(ROOT / "readable" / "src" / "rebased.h"))
    ap.add_argument("--out", default=str(ROOT / "readable" / "tests" / "parity_globals.inc"))
    args = ap.parse_args(argv)

    rows, skipped = parse(Path(args.header))
    lines = [
        "// Generated by readable/tools/gen_parity_globals.py - do not edit.",
        "// Canonical Runtime State: one row per extern \"C\" global declared in",
        "// readable/src/rebased.h, the port's side of tools/parity/state_diff.py.",
        f"// Skipped (incomplete array type): {', '.join(skipped) if skipped else '(none)'}",
        "static const ParityGlobal kParityGlobals[] = {",
    ]
    for sym, note in rows:
        lines.append(f'\t{{"{sym}", sizeof({sym}), &{sym}}},{note and "  // " + note or ""}')
    lines.append("};")
    lines.append(f"static const std::size_t kParityGlobalCount = {len(rows)};")
    out = Path(args.out)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{out}: {len(rows)} rows, {len(skipped)} skipped")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
